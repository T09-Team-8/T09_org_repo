-- Public, read-only event API for the KindDesign website.
CREATE TABLE public.events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  title text NOT NULL,
  event_type text NOT NULL,
  description text,
  starts_at timestamptz,
  venue text,
  image_url text,
  registration_url text
);

COMMENT ON TABLE public.events IS 'Public KindDesign event information served through the Supabase REST API.';
COMMENT ON COLUMN public.events.event_type IS 'Event format, such as meetup, talk, or workshop.';
COMMENT ON COLUMN public.events.starts_at IS 'Event start date and time; remains null until confirmed.';
COMMENT ON COLUMN public.events.venue IS 'Event location; remains null until confirmed.';
COMMENT ON COLUMN public.events.image_url IS 'Optional public image URL for the event.';
COMMENT ON COLUMN public.events.registration_url IS 'Optional signup or event-information URL.';

ALTER TABLE public.events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.events FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.events TO anon, authenticated;
CREATE POLICY "Events are visible to everyone"
  ON public.events
  FOR SELECT
  TO anon, authenticated
  USING (true);
REVOKE ALL ON SEQUENCE public.events_id_seq FROM PUBLIC, anon, authenticated;

-- The Astro product listing only reads. Keep its REST permissions read-only.
REVOKE INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER
  ON TABLE public.products FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.products TO anon, authenticated;
REVOKE ALL ON SEQUENCE public.products_id_seq FROM PUBLIC, anon, authenticated;

-- This is only an internal event-trigger function, not a public RPC endpoint.
REVOKE EXECUTE ON FUNCTION public.rls_auto_enable()
  FROM PUBLIC, anon, authenticated;